import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { analyzeSource } from './analyze.mjs';
import { normalizeOptions, sortDiagnostics } from './source.mjs';
import { compilationPaths } from './paths.mjs';
import { createEmitPlan } from './emit-plan.mjs';
import { emitWorkflow, agentSkillMetadata } from './emit.mjs';
import { checkMermaidIds, renderMermaid } from './mermaid.mjs';
import { commentText } from './values.mjs';

const compilerVersion = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8')).version;

function header(analysis, paths, bodyHash) {
  const nodes = analysis.literal.definition.nodes;
  const has = type => nodes.some(node => node.type === type);
  const conventions = [];
  if (has('condition')) conventions.push('evalWhen reads own ctx.state paths; strict booleans and short circuit; ! has lower precedence than comparison.');
  if (has('agent')) {
    const remoteSkills = [...new Set(nodes.filter(node => node.type === 'agent').map(node => agentSkillMetadata(node, analysis.context.skillsRoot))
      .filter(skill => skill.remote).map(skill => `${skill.reference} (integrity: ${skill.integrity ?? 'not provided'})`))];
    conventions.push('runAgent receives one step; schema -> checkStep -> verify; own-key commit only after success; retries share reasons and control signals are rethrown.' +
      (remoteSkills.length ? ` Remote Skills: ${remoteSkills.join('; ')}.` : ''));
  }
  const interaction = [];
  if (has('human')) interaction.push('runHuman accepts boolean or approved/comment; comment defaults to null.');
  if (has('verification') || nodes.some(node => node.verify != null)) interaction.push('runVerification is strictly boolean (FK_R002).');
  if (interaction.length) conventions.push(interaction.join(' '));
  if (has('action')) conventions.push(`runAction resolve means success; ${analysis.graph.executionEdges.some(edge => edge.role === 'action-failure') ? 'marked action errors set ctx.error and skip the next verification call; ' : ''}other errors reject; control signals are rethrown.`);
  if (has('parallel')) {
    const parallel = nodes.filter(node => node.type === 'parallel');
    const strategies = [];
    if (parallel.some(node => node.join.strategy === 'all_succeeded')) strategies.push('all uses Promise.all first rejection');
    if (parallel.some(node => node.join.strategy === 'any')) strategies.push('any installs control listeners before Promise.any');
    conventions.push(`${strategies.join('; ')}; late results are not cancelled.`);
  }
  const padding = ['Normal completion returns { status, terminal }.', 'Runtime methods are supplied by ctx.runtime.',
    'State is supplied by the host.', 'Source and body hashes are mandatory.', 'This module contains native control flow.'];
  while (conventions.length < 5) conventions.push(padding[conventions.length]);
  const workflow = analysis.literal.definition;
  return ['// @generated by flowkit compiler — DO NOT EDIT', `// workflow: ${commentText(workflow.id)}@${commentText(workflow.version)}（${commentText(workflow.name)}）`,
    `// source: ${paths.source}`, `// sourceHash: sha256:${analysis.snapshot.sourceHash} · bodyHash: sha256:${bodyHash}`,
    `// compiler: flowkit@${compilerVersion} · options: trace=${analysis.context.trace ? 'on' : 'off'}`,
    ...conventions.map(text => `// ${text}`)].join('\n') + '\n';
}

/** The shared internal compiler produces text only; public APIs will own filesystem effects. */
export async function compileToText(snapshot, suppliedOptions = {}) {
  const options = normalizeOptions(suppliedOptions);
  const paths = compilationPaths(snapshot.absFilename, options);
  const analysis = await analyzeSource(snapshot.rawBytes, { ...options, filename: snapshot.absFilename });
  const diagnostics = [...analysis.diagnostics];
  if (analysis.graph) diagnostics.push(...checkMermaidIds(analysis));
  sortDiagnostics(diagnostics);
  if (diagnostics.some(d => d.severity === 'error')) return { code: '', mermaid: '', diagnostics, analysis, plan: null, paths };
  const plan = createEmitPlan(analysis);
  const body = emitWorkflow(analysis, plan);
  const bodyHash = createHash('sha256').update(body.slice(0, -1), 'utf8').digest('hex');
  return { code: header(analysis, paths, bodyHash) + body, mermaid: options.mermaid === false ? '' : renderMermaid(analysis),
    diagnostics, analysis, plan, paths };
}
