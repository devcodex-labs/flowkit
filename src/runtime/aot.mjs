import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const invalid = message => Object.assign(new Error(`FK_R001 ${message}`), { code: 'FK_R001' });

/** Validate one saved artifact snapshot; source containment is lexical, not realpath-based. */
export async function readAOT(filename) {
  const bytes = await readFile(filename);
  let offset = 0;
  for (let line = 0; line < 10; line++) {
    offset = bytes.indexOf(10, offset);
    if (offset < 0) throw invalid('Missing ten-line header');
    offset++;
  }
  let code;
  try { code = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes); }
  catch { throw invalid('Artifact is not UTF-8'); }
  const header = code.split('\n').slice(0, 10);
  if (header[0] !== '// @generated by flowkit compiler — DO NOT EDIT' || header.some(line => !line.startsWith('// '))) throw invalid('Invalid artifact header');
  const hashes = /^\/\/ sourceHash: sha256:([0-9a-f]{64}) · bodyHash: sha256:([0-9a-f]{64})$/.exec(header[3]);
  if (!hashes || !header[2].startsWith('// source: ')) throw invalid('Missing source/hash fields');
  const source = header[2].slice('// source: '.length);
  let segments;
  try { segments = source.split('/').map(decodeURIComponent); }
  catch { throw invalid('Malformed source path encoding'); }
  if (!source || segments.some(segment => !segment || segment === '..' || /[\\/\0]/.test(segment)) || /^[A-Za-z]:/.test(segments[0])) throw invalid('Source path must remain relative');
  const directory = path.dirname(filename);
  const sourceFile = path.resolve(directory, ...segments);
  const relative = path.relative(directory, sourceFile);
  if (!relative || path.isAbsolute(relative) || relative.split(path.sep).includes('..')) throw invalid('Source escapes artifact directory');
  let raw;
  try { raw = await readFile(sourceFile); }
  catch (error) { if (['ENOENT', 'ENOTDIR'].includes(error?.code)) throw invalid('Source file is missing'); throw error; }
  const body = bytes.subarray(offset);
  const bodyBytes = body.at(-1) === 10 ? body.subarray(0, -1) : body;
  if (hash(raw) !== hashes[1] || hash(bodyBytes) !== hashes[2]) throw invalid('Source or body hash differs');
  return code;
}
